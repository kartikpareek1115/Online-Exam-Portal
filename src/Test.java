    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        try{
             String question = q_question.getText();
        String A = q_a.getText();
        String B = q_b.getText();
        String C = q_c.getText();
        String D = q_d.getText();
        String correct = q_correctAns.getSelectedItem().toString();
        
        Class.forName("com.mysql.cj.jdbc.Driver");
        
        Connection cn = DriverManager.getConnection("jdbc:mysql://localhost:3306/OnlineExam","root","MySql@123");
        
        PreparedStatement ps = cn.prepareStatement("insert into questions( question, option_a, option_b, option_c, option_d,correct_option) values(?,?,?,?,?,?)");
        ps.setString(1, question);
        ps.setString(2, A);
        ps.setString(3, B);
        ps.setString(4, C);
        ps.setString(5, D);
        ps.setString(6, correct);
        
        int rows = ps.executeUpdate();
        if (rows > 0) {
            JOptionPane.showMessageDialog(this, "Question Added Successfully!");
            // Clear fields after adding
            q_question.setText("");
            q_a.setText("");
            q_b.setText("");
            q_c.setText("");
            q_d.setText("");
            q_correctAns.setSelectedIndex(0);
        }
        else{
            System.out.println("Question not inserted!!");
        }

        cn.close();
        }
        catch(Exception e){
            System.out.println(e);
        }
       
    }//GEN-LAST:event_jButton3ActionPerformed

