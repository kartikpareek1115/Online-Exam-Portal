    private void loadQuestionsFromDB() {
    try {
        Class.forName("com.mysql.cj.jdbc.Driver");
        Connection cn = DriverManager.getConnection(
            "jdbc:mysql://localhost:3306/OnlineExam", "root", "MySql@123"
        );
        PreparedStatement ps = cn.prepareStatement("SELECT * FROM questions");
        ResultSet rs = ps.executeQuery();

        while (rs.next()) {
            String[] q = new String[6];
            q[0] = rs.getString("question");
            q[1] = rs.getString("option_a");
            q[2] = rs.getString("option_b");
            q[3] = rs.getString("option_c");
            q[4] = rs.getString("option_d");
            q[5] = rs.getString("correct_option");
            questions.add(q);
        }
        System.out.println("Questions loaded: " + questions.size());
        cn.close();

    } catch (Exception e) {
        System.out.println(e);
    }
}

private void showQuestion() {
    if (currentIndex >= questions.size()) {
        submitExam();
        return;
    }

    String[] q = questions.get(currentIndex);

    questionNumber.setText("Question " + (currentIndex + 1) + " of " + questions.size());
    questionLabel.setText(q[0]);
    optA.setText("A.  " + q[1]);
    optB.setText("B.  " + q[2]);
    optC.setText("C.  " + q[3]);
    optD.setText("D.  " + q[4]);

    buttonGroup2.clearSelection();
}


private void submitExam() {
   
    

    // calculate score
    int score = 0;
    for (int i = 0; i < studentAnswers.size(); i++) {
        if (studentAnswers.get(i).equals(questions.get(i)[5])) {
            score++;
        }
    }

    int total = questions.size();
    int wrong = studentAnswers.size() - score;

    // show result
    JOptionPane.showMessageDialog(this,
        "Exam Finished!\n\n" +
        "Total Questions : " + total + "\n" +
        "Correct Answers : " + score + "\n" +
        "Wrong Answers   : " + wrong + "\n\n" +
        "Your Score      : " + score + " / " + total
    );

    // switch to result tab automatically
    jTabbedPane1.setSelectedIndex(4);

    // show score in result tab
    jLabel18.setText("Your Score: " + score + " / " + total);
}


